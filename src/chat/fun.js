function validateArgs(name, args) {
  const schema = FUN_TOOLS.find(t => t.name === name)?.input_schema;
  if (!schema || !args || typeof args !== 'object' || Array.isArray(args)) throw Error('操作資料格式不正確。');
  for (const [key, value] of Object.entries(args)) {
    const p = schema.properties[key];
    if (!p || (p.type === 'integer' ? !Number.isInteger(value) || value < p.minimum || value > p.maximum : typeof value !== p.type) ||
      p.enum && !p.enum.includes(value) || p.maxLength && [...value].length > p.maxLength) throw Error(`欄位 ${key} 不正確。`);
  }
}

// Persist the chosen result before posting; retries use the same Discord nonce
// and the same random result. Large PNGs are regenerated rather than stored.
export async function executeFunTool(env, event, job, state, save, fetcher = fetch) {
  const marker = job.toolResults[event.id];
  if (marker.funResult) return marker.funResult;
  if (!String(env.ALLOWED_GUILD_IDS || '').split(',').includes(job.input.guildId)) return { status: 'unavailable', message: '此伺服器未啟用這項功能。' };
  try {
    validateArgs(event.name, event.input || {});
    const args = event.input || {};
    if (!marker.funPrepared) {
      if (Object.values(job.toolResults).filter(m => m.funPrepared).length >= 3) throw Error('每則訊息最多執行三次娛樂操作。');
      let payload, draft;
      if (event.name === 'roll_dice') {
        const r = roll(args.dice);
        payload = { content: `🎲 **${r.expression}** → ${r.rolls.join(' + ')}${r.modifier ? ` ${r.modifier > 0 ? '+' : '−'} ${Math.abs(r.modifier)}` : ''} = **${r.total}**` };
      } else if (event.name === 'pick_random_craft') payload = { content: `🎲 這次玩 **${CRAFTS[randomInt(7) + 1]}**！` };
      else if (event.name === 'pick_random_card') payload = await randomCard(args, fetcher);
      else if (event.name === 'make_custom_card') {
        const previous = state.lastFunCard;
        if (args.reuse_previous && (!previous || previous.authorId !== job.input.authorId)) throw Error('找不到你先前製作的卡片，請提供卡片內容。');
        const { reuse_previous, artwork_index, clear_artwork, card_slot = 1, ...fields } = args;
        for (const key of ['effect', 'evolved', 'superEvolved']) if (typeof fields[key] === 'string') fields[key] = fields[key].replace(/\\r\\n|\\n/g, '\n');
        const card = validateCard({ ...(reuse_previous ? previous.card : {}), ...fields });
        let artwork = reuse_previous && !clear_artwork ? previous.artwork : undefined;
        if (artwork_index !== undefined) {
          artwork = job.input.images?.[artwork_index - 1];
          if (!artwork || !['image/png', 'image/jpeg', 'image/webp'].includes(artwork.mediaType)) throw Error('請指定本則上傳或回覆的 PNG/JPEG/WebP 立繪；未送出空白卡。');
        } else if (!clear_artwork && !artwork && job.input.images?.length === 1) {
          artwork = job.input.images[0];
        } else if (!clear_artwork && !artwork && job.input.images?.length > 1) {
          throw Error('本則有多張圖片，請用 artwork_index 指定立繪；未送出空白卡。');
        }
        if (job.artworkRequired && !artwork) throw Error('立繪仍未成功讀取，不能移除附件改送空白卡。');
        if (artwork) { job.artworkRequired = true; await save(); }
        draft = { card, ...(artwork ? { artwork } : {}), authorId: job.input.authorId };
        payload = { content: '你的自訂卡片完成了！',
          embeds: [{ title: card.name, image: { url: 'attachment://custom-card.png' }, footer: { text: '自訂卡片' } }],
          attachments: [{ id: 0, filename: 'custom-card.png', description: '自訂卡片（非官方卡片）' }] };
      }
      marker.funPrepared = { payload, ...(draft ? { draft, slot: args.card_slot || 1 } : {}) };
      await save();
    }
    const { payload, draft, slot } = marker.funPrepared;
    const priorDelivery = draft && job.customCards?.[slot];
    if (priorDelivery && JSON.stringify(priorDelivery.draft) === JSON.stringify(draft)) {
      marker.funResult = priorDelivery.result; await save(); return marker.funResult;
    }
    let png;
    if (draft) {
      if (!env.FUN || !env.FUN_API_TOKEN) throw Error('製卡服務尚未連線。');
      const card = { ...draft.card };
      if (draft.artwork) {
        card.artwork = await loadArtwork(env, draft.artwork, fetcher);
      }
      validateCard(card);
      const response = await env.FUN.fetch('https://fun/v1/cards/render', { method: 'POST',
        headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${env.FUN_API_TOKEN}` }, body: JSON.stringify(card) });
      if (!response.ok) {
        if (response.status === 400) throw Error((await response.json()).error || '製卡資料不正確。');
        throw Error(response.status === 429 ? '製卡服務已達使用上限，請稍後再試。' : '製卡服務暫時無法使用，請稍後再試。');
      }
      if (!response.headers.get('content-type')?.startsWith('image/png')) throw Error('製卡服務未回傳圖片。');
      png = await boundedBytes(response, 8 * 1024 * 1024);
    }
    const body = { ...payload, flags: 0, allowed_mentions: { parse: [], replied_user: false },
      nonce: await messageNonce(`fun:${job.input.id}:${draft ? `card-${slot}` : event.id}`), enforce_nonce: true,
      message_reference: { message_id: job.input.id, fail_if_not_exists: false } };
    let post = body;
    if (png) {
      post = new FormData(); post.set('payload_json', JSON.stringify(body));
      post.set('files[0]', new Blob([png], { type: 'image/png' }), 'custom-card.png');
    }
    // Same-turn corrections update their existing attachment, including across
    // model tool-call IDs and restarts. The first card can replace interim text.
    const target = priorDelivery?.result.messageId || (draft && slot === 1 ? job.input.progressMessageId : undefined);
    let sent;
    try { sent = await discord(env, `/channels/${job.input.channelId}/messages${target ? `/${target}` : ''}`, target ? 'PATCH' : 'POST', post, fetcher); }
    catch (error) {
      if (!target || error.status !== 404) throw error;
      sent = await discord(env, `/channels/${job.input.channelId}/messages`, 'POST', post, fetcher);
    }
    marker.funResult = { status: 'ok', delivered: true, messageId: sent.id,
      result: draft ? { card: draft.card, artwork: draft.artwork ? 'user attachment' : 'maker default' } : payload };
    if (draft) {
      state.lastFunCard = draft;
      job.customCards ||= {}; job.customCards[slot] = { draft, result: marker.funResult };
      if (slot === 1) { job.input.progressMessageId = sent.id; delete job.input.progressUnavailable; }
    }
    await save();
    return marker.funResult;
  } catch (error) {
    // Discord/network failures can be retried by the persisted conversation job.
    if (error.status || error instanceof TypeError || error.name === 'TimeoutError' || error.name === 'AbortError') throw error;
    marker.funResult = { status: 'unavailable', message: String(error.message).slice(0, 300) };
    await save();
    return marker.funResult;
  }
}
